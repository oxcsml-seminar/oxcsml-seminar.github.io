"""Build site/assets/js/data.js from data/talks/*.yml and data/terms.yml."""
import json
import re
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).parent
FIELDS = {"date", "time", "endTime", "room", "speaker", "affiliation", "speakerUrl",
          "title", "abstract", "slides", "zoomUrl", "status"}
TIME, URL = (r"([01]\d|2[0-3]):[0-5]\d", "HH:MM"), (r"https?://\S+", "an http(s):// link")
FORMATS = {"time": TIME, "endTime": TIME, "speakerUrl": URL, "zoomUrl": URL,
           "status": (r"confirmed|provisional", "confirmed or provisional")}


def load(path):
    # BaseLoader keeps every value a string, so 15:00 and 2026-11-27 are not reinterpreted.
    return yaml.load(path.read_text(encoding="utf-8"), Loader=yaml.BaseLoader) or {}


def valid_date(s):
    try:
        return bool(re.fullmatch(r"\d{4}-\d{2}-\d{2}", s) and date.fromisoformat(s))
    except ValueError:
        return False


def problems(talk):
    yield from (f"unknown field '{k}'" for k in sorted(talk.keys() - FIELDS))
    if not valid_date(talk.get("date", "")):
        yield f"date '{talk.get('date', '')}' should be a valid YYYY-MM-DD date"
    yield from (f"{k} '{talk[k]}' should be {hint}" for k, (p, hint) in FORMATS.items()
                if talk.get(k) and not re.fullmatch(p, talk[k]))


talks, errors = [], []
for path in sorted((ROOT / "data/talks").glob("[!_]*.y*ml")):
    try:
        talk = load(path)
        errors += [f"{path.name}: {e}" for e in problems(talk)]
        talks.append({"id": path.stem, **talk})
    except yaml.YAMLError as e:
        errors.append(f"{path.name}: {e}")
if errors:
    sys.exit("\n".join(errors))

terms = [{**t, "year": int(t["year"])} for t in load(ROOT / "data/terms.yml")]
dump = lambda x: json.dumps(x, indent=2, ensure_ascii=False)
(ROOT / "site/assets/js/data.js").write_text(
    "// Generated by build.py from data/; do not edit.\n"
    f"window.OXCSML_TALKS = {dump(sorted(talks, key=lambda t: t['date']))};\n"
    f"window.OXCSML_TERMS = {dump(terms)};\n", encoding="utf-8")
print(f"Wrote site/assets/js/data.js with {len(talks)} talks.")
